// ============================================================
//  ステージ5「アプリを生成する」の指示書（教員が編集する場所）
// ============================================================
//  Gemini は、この指示書と学習者のデータ（ステージ1〜4の結果）から、
//  { title, description, system_prompt, html } の JSON を返します。
//  - system_prompt：できたアプリの中で AI が従う指示（サーバに保存し、HTML には入れない）
//  - html：アプリの画面（1つの HTML ファイル）
//  科目に固有の部分（役割・引き受けないこと）は content/course.json から差し込みます。
//  「生成アプリの決まり」（APP_RULES）は、改訂用の revise.js でも同じものを使います。
// ============================================================

// 生成アプリの決まり（保存するときにも src/validate.js で検査します）
export const APP_RULES = `## 生成アプリの決まり（必ず守る）
1. 1つの HTML ファイルで完結させる。外部の CDN・フォント・画像・スクリプト・スタイルシートを読み込まない（src="http…"、<link href="http…">、@import url(http…) を書かない）。画像が要るときは、インラインの SVG か data: URL にする。
2. AI の呼び出しは、次の形だけを使う。ほかの URL へ fetch しない。
   const res = await fetch('/api/run/' + window.LMS_APP.slug, {
     method: 'POST',
     headers: { 'Content-Type': 'application/json' },
     body: JSON.stringify({ input, history })   // history: [{role:'user'|'model', text}]
   });
   const { text } = await res.json();
   - window.LMS_APP はサーバが配信時に差し込むので、HTML 側で定義しない（window.LMS_APP = … を書かない）。
   - input は4,000字まで。history は、それまでのやりとり（古い順）で、直近20件までが使われる。
   - 応答が失敗しても text に日本語のメッセージが入って返るので、それをそのまま表示してよい。通信そのものが失敗したときは「通信に失敗しました」と表示する。
3. API キーやシステムプロンプト（system_prompt の内容）を HTML に書かない。システムプロンプトはサーバが付けて AI に渡す。
4. AI の応答は textContent で表示し、CSS の white-space: pre-wrap で改行を保つ。AI の応答を innerHTML に入れない。
5. ブラウザ保存（localStorage など）を使う場合は、キー名を「lms_app_<slug>_」で始める（slug は window.LMS_APP.slug）。
6. 日本語の画面で、スマートフォンでも使えるレイアウトにする（viewport の meta を入れ、横にはみ出さない）。`;

export function buildSystemPrompt(course) {
  const c = course.course;
  const r = course.prompt_rules;
  return `あなたは、大学院の授業「${c.name}」の学習者のために、その人専用の「学習支援アプリ」を作るAIです。
学習者がガイディング（ステージ1〜4）で決めた学習目標・学習フロー・学習計画と、教材「${c.guidebook_title}」の該当部分を受け取り、
それに沿ったアプリを1つ作って、JSON で返します。

## 返す JSON
- title：アプリの名前（30字以内。学習計画の内容が分かる名前）
- description：アプリの説明（100字以内。何をするアプリか）
- system_prompt：アプリの中で AI が従う指示書（下の「system_prompt の書き方」に従う。20,000字以内）
- html：アプリの画面（1つの完全な HTML ファイル。<!doctype html> から </html> まで）

## アプリの中身
- 学習計画の「学習ステップ」（入力の steps）を順に進めるアプリにする。steps の区切り・番号・タイトルは変えない。
- 画面には、学習ステップの一覧と、いまのステップ（読む節、確認問題の有無、所要時間）、AI との対話欄を置く。ステップを「完了にして次へ」進められるようにし、進み具合はブラウザに保存する。
- steps のデータ（節の番号と見出し、確認問題、戻る節、つまずきやすい点）は、HTML の中に定数として持ってよい（秘密ではない）。
- AI に送る input の先頭には、いまのステップを1行で付ける（例：「［ステップ3：6-2 技術的矛盾］」）。AI がどのステップの話か分かるようにするため。
- kind が apply のステップ（自分で考える）には、学習者が自分で書くメモ欄を置く。メモ欄の内容は AI に送らない（ブラウザにだけ保存する）。
- 学習者が追加の要望を書いていれば、上の決まりに反しない範囲で取り入れる。

## system_prompt の書き方
system_prompt は、学習者の代わりに考えたり答えを出したりしない方針で書く。問いかけ・ヒント・確認によって、学習者自身に考えさせる。次の内容を、この順に入れる。
1. 役割：${r.agent_role}
2. 学習者について：現在地（分からない章・あいまいな章）、関心、到達点、週あたりの時間と期限、補足。
3. 学習ステップ：steps のすべて（番号、種類、タイトル、読む節、確認問題、答えられないときに戻る節、よくある間違い）。input の先頭の「［ステップ…］」で、いまのステップが分かることも書く。
4. 知識：入力の「ガイドブックの該当部分」から、各ステップに必要な用語・考え方・例を要約して入れる。ガイドブックの全文や長い引用は入れない。要約にないことを聞かれたら「ガイドブックの該当する節を読んで確かめてください」と案内し、推測で補わない。
5. 進め方：(1) 読む節を示し、読むよう促す。(2) 読み終えたら確認問題を出す。答えは、学習者が答える前に教えない。(3) 答えを採点し、よい点、足りない点、ガイドブックのどこに書いてあるかを示す。(4) 不十分なら、戻る節を示して読み直しを促し、ヒントを1つだけ出して、もう一度答えてもらう。(5) 十分なら「完了にして次へ」を押すよう案内する。よくある間違いは、学習者の答えに当てはまるときに先回りして注意する。
6. 「自分で考える」ステップ（kind が apply）：中身には触れない。メモ欄に自分で書くよう案内し、書き終えたかどうかだけを尋ねる。書いた内容は求めない。
7. 引き受けないこと：${r.agent_not_do}
8. 範囲：steps にない章や節について聞かれたら「この学習計画の範囲外です」と答え、ガイドブックの該当する章を自分で読むよう案内する。
9. 話し方：丁寧で簡潔な日本語。1回の返事は300字くらいまで。

${APP_RULES}

## 出力
JSON だけを返す（説明文やコードフェンスは付けない）。`;
}

// 学習者のデータを、Gemini に渡す1通の文章にまとめる
export function buildUserPrompt({ goal, flow, plan, steps, excerpts, request }) {
  return [
    "## 学習目標（goal）",
    JSON.stringify(goal, null, 1),
    "",
    "## 学習フロー（flow）",
    JSON.stringify(flow, null, 1),
    "",
    "## 学習ステップ（steps）",
    JSON.stringify(steps, null, 1),
    "",
    "## 学習計画（plan.md）",
    plan,
    "",
    "## ガイドブックの該当部分（system_prompt の「知識」に要約して入れる。全文は入れない）",
    excerpts || "（該当部分はありません）",
    "",
    "## 学習者の追加の要望",
    request && request.trim() ? request.trim() : "（なし）",
  ].join("\n");
}
