// ============================================================
//  ステージ5「アプリを生成する」の指示書（教員が編集する場所）
// ============================================================
//  Gemini は、この指示書と学習者のデータ（ステージ1〜4の結果）から、
//  { title, description, system_prompt, html } の JSON を返します。
//  - system_prompt：できたアプリの中で AI が従う指示（サーバに保存し、HTML には入れない）
//  - html：アプリの画面（1つの HTML ファイル）
//  科目に固有の部分（役割・引き受けないこと）は content/course.json から差し込みます。
//  「生成アプリの決まり」（APP_RULES）は、改訂用の revise.js でも同じものを使います。
// ============================================================

// 生成アプリの決まり（保存するときにも src/validate.js で検査します）
export const APP_RULES = `## 生成アプリの決まり（必ず守る）
1. 1つの HTML ファイルで完結させる。外部の CDN・フォント・画像・スクリプト・スタイルシートを読み込まない（src="http…"、<link href="http…">、@import url(http…) を書かない）。画像が要るときは、インラインの SVG か data: URL にする。
2. AI の呼び出しは、次の形だけを使う。fetch してよいのは、この /api/run/ と、決まり7の /api/state/ だけ。
   const res = await fetch('/api/run/' + window.LMS_APP.slug, {
     method: 'POST',
     headers: { 'Content-Type': 'application/json' },
     body: JSON.stringify({ input, history, step })   // history: [{role:'user'|'model', text}]、step: いまのステップの番号（整数）
   });
   const { text, check } = await res.json();
   - step は必ず送る（どのステップのやりとりかを、学習の記録に残すため）。
   - check は、その返事が確認問題の採点だったかどうか（"pass"＝十分、"retry"＝もう一度、"none"＝採点ではない）。"pass" のときは「完了にして次へ」を目立たせてよい。check の値を理由にステップを勝手に進めたり、止めたりはしない。
   - window.LMS_APP はサーバが配信時に差し込むので、HTML 側で定義しない（window.LMS_APP = … を書かない）。
   - input は4,000字まで。history は、それまでのやりとり（古い順）で、直近20件までが使われる。
   - 応答が失敗しても text に日本語のメッセージが入って返るので、それをそのまま表示してよい。通信そのものが失敗したときは「通信に失敗しました」と表示する。
3. API キーやシステムプロンプト（system_prompt の内容）を HTML に書かない。システムプロンプトはサーバが付けて AI に渡す。
4. AI の応答は textContent で表示し、CSS の white-space: pre-wrap で改行を保つ。AI の応答を innerHTML に入れない。
5. ブラウザ保存（localStorage など）を使う場合は、キー名を「lms_app_<slug>_」で始める（slug は window.LMS_APP.slug）。ただし、進み具合・会話の履歴・メモは、決まり7のとおりサーバに保存する（ブラウザ保存だけにしない）。
6. 日本語の画面で、スマートフォンでも使えるレイアウトにする（viewport の meta を入れ、横にはみ出さない）。
7. 学習の中断と再開ができるようにする。状態（進み具合・各ステップの会話の履歴・メモ）は、次の形でサーバに保存する。パソコンで中断してスマートフォンで再開できるようにするため。
   // 読む（アプリを開いたとき）
   const res = await fetch('/api/state/' + window.LMS_APP.slug);
   const { state, updated_at } = await res.json();   // 保存が無いときは state が null
   // 保存する
   await fetch('/api/state/' + window.LMS_APP.slug, {
     method: 'POST',
     headers: { 'Content-Type': 'application/json' },
     body: JSON.stringify({ state })   // state は JSON のオブジェクト。{ state: null } で消える
   });
   - state には、進み具合（下の progress）、ステップごとの会話の履歴、メモ欄の内容、中断した日時、steps の区切りが分かる情報（ステップ数とタイトルの一覧など）を入れる。
   - 進み具合は、必ず次の形で state.progress に入れる（LMS の学習分析がこの形を読む。名前と値を変えない）。
     progress: {
       current: 2,                                   // いまのステップの番号
       steps: [                                      // steps のすべてを、番号の順に
         { no: 1, status: "done",  self: "known" },  // status: "done"＝完了 / "doing"＝いま取り組んでいる / "todo"＝まだ
         { no: 2, status: "doing", self: null },     // self: 完了したときの自己評価。"known"＝分かった / "unsure"＝あいまい / "unknown"＝分からない / まだなら null
         { no: 3, status: "todo",  self: null }
       ]
     }
   - 自己評価：kind が read のステップで「完了にして次へ」を押したとき、「このステップの内容は、どのくらい分かりましたか」と尋ね、「分かった」「あいまい」「分からない」の3つから選んでもらってから次へ進む。選んだ値を、そのステップの self に入れる。kind が apply のステップでは尋ねない（self は null のまま）。「あいまい」「分からない」を選んでも次へ進める（戻る節を一言案内する）。
   - state は 200KB まで。大きくなりそうなときは、各ステップの会話の古い分から減らす。
   - 保存する時機：メッセージを送って返事が来たとき、ステップを進めたとき、メモを書いたとき（入力のたびではなく、少し間をおいて）、「学習を一時中断する」を押したとき。
   - 画面の上部（進み具合の表示の近く）に「学習を一時中断する」ボタンを置く。押したら保存し、「中断しました。このページを閉じても、次に開いたときに続きから再開できます」と表示する。保存に失敗したら、その旨を表示する。
   - アプリを開いたとき、保存があれば、中断した日時とステップを示して「中断した箇所から学習を再開する」と「最初からやり直す」のボタンを出す。再開を選んだら、会話の履歴とメモを画面に戻す。やり直しを選んだら、確認してから { state: null } を送って消す。
   - 保存してある state の steps の区切りが、いまのアプリの steps と合わないとき（作り直しでステップが変わったとき）は、その旨を示して「最初からやり直す」を勧める。
   - 読み込みや保存の通信が失敗しても、アプリは使い続けられるようにする（「保存できませんでした」と小さく表示する）。
8. 文字の大きさは、学習者が LMS の「アプリ設定」で変える。サーバが html 要素の font-size を設定に合わせて差し込むので、次を守る。
   - html 要素（:root）の font-size を、HTML 側で指定しない。
   - 文字の大きさ（font-size）は、すべて rem で書く（例：本文 1rem、小さい字 0.85rem、見出し 1.25rem）。px では書かない。
   - 文字に合わせて広がるべき余白や高さ（ボタン、入力欄、吹き出しの内側の余白など）も rem で書く。
   - 文字が大きくなっても、横にはみ出したり、入力欄や送信ボタンが画面の外に出たりしないレイアウトにする。`;

export function buildSystemPrompt(course) {
  const c = course.course;
  const r = course.prompt_rules;
  return `あなたは、大学院の授業「${c.name}」の学習者のために、その人専用の「学習支援アプリ」を作るAIです。
学習者がガイディング（ステージ1〜4）で決めた学習目標・学習フロー・学習計画と、教材「${c.guidebook_title}」の該当部分を受け取り、
それに沿ったアプリを1つ作って、JSON で返します。

## 返す JSON
- title：アプリの名前（30字以内。学習計画の内容が分かる名前）
- description：アプリの説明（100字以内。何をするアプリか）
- system_prompt：アプリの中で AI が従う指示書（下の「system_prompt の書き方」に従う。20,000字以内）
- html：アプリの画面（1つの完全な HTML ファイル。<!doctype html> から </html> まで）

## アプリの中身
- 学習計画の「学習ステップ」（入力の steps）を順に進めるアプリにする。steps の区切り・番号・タイトルは変えない。
- 画面には、学習ステップの一覧と、いまのステップ（読む節、確認問題の有無、所要時間）、AI との対話欄を置く。ステップを「完了にして次へ」進められるようにし、進み具合は決まり7のとおりサーバに保存する。
- steps のデータ（節の番号と見出し、確認問題、戻る節、つまずきやすい点）は、HTML の中に定数として持ってよい（秘密ではない）。
- AI に送る input の先頭には、いまのステップを1行で付ける（例：「［ステップ3：6-2 技術的矛盾］」）。AI がどのステップの話か分かるようにするため。
- kind が apply のステップ（自分で考える）には、学習者が自分で書くメモ欄を置く。メモ欄の内容は AI に送らない（/api/run/ の input にも history にも入れない）。保存は、決まり7の state に入れて行う。
- AI に送る history は、いまのステップの会話だけにする（再開したあとも、保存してあった会話の続きとして送る）。
- 学習者が追加の要望を書いていれば、上の決まりに反しない範囲で取り入れる。

## system_prompt の書き方
system_prompt は、学習者の代わりに考えたり答えを出したりしない方針で書く。問いかけ・ヒント・確認によって、学習者自身に考えさせる。次の内容を、この順に入れる。
1. 役割：${r.agent_role}
2. 学習者について：現在地（分からない章・あいまいな章）、関心、到達点、週あたりの時間と期限、補足。
3. 学習ステップ：steps のすべて（番号、種類、タイトル、読む節、確認問題、答えられないときに戻る節、よくある間違い）。input の先頭の「［ステップ…］」で、いまのステップが分かることも書く。
4. 知識：入力の「ガイドブックの該当部分」から、各ステップに必要な用語・考え方・例を要約して入れる。ガイドブックの全文や長い引用は入れない。要約にないことを聞かれたら「ガイドブックの該当する節を読んで確かめてください」と案内し、推測で補わない。
5. 進め方：(1) 読む節を示し、読むよう促す。(2) 読み終えたら確認問題を出す。答えは、学習者が答える前に教えない。(3) 答えを採点し、よい点、足りない点、ガイドブックのどこに書いてあるかを示す。(4) 不十分なら、戻る節を示して読み直しを促し、ヒントを1つだけ出して、もう一度答えてもらう。(5) 十分なら「完了にして次へ」を押すよう案内する。よくある間違いは、学習者の答えに当てはまるときに先回りして注意する。
6. 「自分で考える」ステップ（kind が apply）：中身には触れない。メモ欄に自分で書くよう案内し、書き終えたかどうかだけを尋ねる。書いた内容は求めない。
7. 引き受けないこと：${r.agent_not_do}
8. 範囲：steps にない章や節について聞かれたら「この学習計画の範囲外です」と答え、ガイドブックの該当する章を自分で読むよう案内する。
9. 話し方：丁寧で簡潔な日本語。1回の返事は300字くらいまで。返事は画面に文字のまま表示されるので、Markdown の記法（**太字**、# 見出し、--- の区切り線など）は使わず、ふつうの文章と改行で書く。箇条書きは「・」で始める。

${APP_RULES}

## 出力
JSON だけを返す（説明文やコードフェンスは付けない）。`;
}

// 学習者のデータを、Gemini に渡す1通の文章にまとめる
export function buildUserPrompt({ goal, flow, plan, steps, excerpts, request }) {
  return [
    "## 学習目標（goal）",
    JSON.stringify(goal, null, 1),
    "",
    "## 学習フロー（flow）",
    JSON.stringify(flow, null, 1),
    "",
    "## 学習ステップ（steps）",
    JSON.stringify(steps, null, 1),
    "",
    "## 学習計画（plan.md）",
    plan,
    "",
    "## ガイドブックの該当部分（system_prompt の「知識」に要約して入れる。全文は入れない）",
    excerpts || "（該当部分はありません）",
    "",
    "## 学習者の追加の要望",
    request && request.trim() ? request.trim() : "（なし）",
  ].join("\n");
}
